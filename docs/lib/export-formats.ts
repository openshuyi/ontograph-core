import { DotExporter } from "@ontograph/core/exporters/dot-exporter";
import { JsonSchemaExporter } from "@ontograph/core/exporters/json-schema-exporter";
import { MermaidExporter } from "@ontograph/core/exporters/mermaid-exporter";
import { OWLExporter } from "@ontograph/core/exporters/owl-exporter";
import { SHACLExporter } from "@ontograph/core/exporters/shacl-exporter";
import { Neo4jSchemaGenerator } from "@ontograph/core/transformer";
import type {
  AttributeDefinition,
  OntologyDefinition,
} from "@ontograph/core/types";
import type { OntologyEditorState } from "./editor-types";

/**
 * Export format generators for the docs editor / exports demo.
 *
 * All standard formats (OWL, SHACL, JSON Schema, Mermaid, DOT, Neo4j Cypher)
 * are generated by the REAL exporters from `@ontograph/core`, so the docs
 * always show authoritative output. Only `generateTypeScript` (builder-code
 * scaffolding, which core does not provide) is implemented here.
 */

function localName(id: string): string {
  return id.includes(":") ? (id.split(":")[1] ?? id) : id;
}

/** Adapt the editor's simplified state into a real `OntologyDefinition` */
export function toOntologyDefinition(
  state: OntologyEditorState,
): OntologyDefinition {
  const attributes: AttributeDefinition[] = [];
  const seenAttrs = new Set<string>();
  for (const entity of state.entities) {
    for (const attrRef of entity.attributes) {
      if (seenAttrs.has(attrRef.ref)) continue;
      seenAttrs.add(attrRef.ref);
      attributes.push({
        "@id": attrRef.ref,
        "@type": "Attribute",
        label: { en: localName(attrRef.ref) },
        datatype: "string",
        required: attrRef.required,
        identity: attrRef.identity,
      });
    }
  }

  return {
    "@context": {
      ontograph: "https://ontograph.app/ontology/scm#",
      scm: "http://example.com/supplychain#",
    },
    "@id": "scm:EditorOntology",
    "@type": "Ontology",
    version: "1.0.0",
    label: { en: "Editor Ontology" },
    entityTypes: state.entities.map((entity) => ({
      "@id": entity.id,
      "@type": "EntityType",
      label: { en: entity.label },
      description: entity.description ? { en: entity.description } : undefined,
      kind: entity.kind,
      extends: entity.extends,
      attributes: entity.attributes.map((a) => ({
        ref: a.ref,
        required: a.required,
        identity: a.identity,
      })),
      relations: state.relations
        .filter((r) => r.source === entity.id)
        .map((r) => ({ ref: r.id })),
      constraints: state.constraints
        .filter((c) => c.entityType === entity.id)
        .map((c) => ({ ref: c.id })),
      ui: entity.color ? { color: entity.color, icon: entity.icon } : undefined,
    })),
    relationTypes: state.relations.map((r) => ({
      "@id": r.id,
      "@type": "RelationType",
      label: { en: r.label },
      description: r.description ? { en: r.description } : undefined,
      domain: r.source,
      range: r.target,
      inverse: r.inverse,
    })),
    attributes,
    constraints: state.constraints.map((c) => ({
      "@id": c.id,
      "@type": "Constraint",
      label: { en: c.label },
      on: c.entityType,
      rule: c.expression,
    })),
  };
}

export function generateOWL(state: OntologyEditorState): string {
  return new OWLExporter(toOntologyDefinition(state)).export();
}

export function generateSHACL(state: OntologyEditorState): string {
  return new SHACLExporter(toOntologyDefinition(state)).export();
}

export function generateJsonSchema(state: OntologyEditorState): string {
  return new JsonSchemaExporter(toOntologyDefinition(state)).exportString();
}

export function generateMermaid(state: OntologyEditorState): string {
  return new MermaidExporter(toOntologyDefinition(state)).export();
}

export function generateDot(state: OntologyEditorState): string {
  return new DotExporter(toOntologyDefinition(state)).export();
}

export function generateNeo4jCypher(state: OntologyEditorState): string {
  return new Neo4jSchemaGenerator(toOntologyDefinition(state))
    .generate()
    .join("\n");
}

export function generateTypeScript(state: OntologyEditorState): string {
  const entityDefs = state.entities
    .map((e) => {
      let code = `defineEntity("${e.id}", { label: { en: "${e.label}" }, kind: "${e.kind}" })`;
      for (const a of e.attributes) {
        const req = a.required ? "true" : "false";
        const identity = a.identity ? ", identity: true" : "";
        code += `\n  .attr("${a.ref}", { required: ${req}${identity} })`;
      }
      code += "\n  .build()";
      return code;
    })
    .join("\n\n");

  const relationDefs = state.relations
    .map((r) => {
      return `defineRelation("${r.id}", { label: { en: "${r.label}" } }, "${r.source}", "${r.target}")`;
    })
    .join("\n\n");

  const lines = [
    'import { defineEntity, defineRelation } from "@ontograph/core";',
    "",
    "// Entities",
    "",
    entityDefs,
    "",
    "// Relations",
    "",
    relationDefs,
  ];

  return lines.join("\n");
}
